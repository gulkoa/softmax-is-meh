#!/bin/bash
# Cleanup of 2026-11-09, on the user's instruction of that morning: remove
# the third-party models not in use, the MQMTAR data, and everything that
# can be regenerated easily. Explicit absolute paths only; each is printed
# with its size and then removed. DRY=1 prints the sizes without removing.
#
#   bash scripts/cleanup_2026-11-09.sh 2>&1 | tee results/cleanup-2026-11-09.log
#   DRY=1 bash scripts/cleanup_2026-11-09.sh
#
# Removed, and how each comes back:
#   results/mqmtar_data              synthetic MQMTAR data (3M and 50M sets);
#                                    the 50M set is regenerated by
#                                    slurm/mqmtar_datagen_50m_cpu.sh, the 3M
#                                    set by the same generator (see the
#                                    roadmap housekeeping note)
#   ~/.cache/huggingface/hub/models--*  every entry except models--gpt2, which
#                                    the convert and upload tools read; all of
#                                    them are Hub downloads (Gemma 2 2B, the
#                                    SAEBench Gemma SAE, Gemma 1.1 2B-it,
#                                    T5-small, GPT-2 medium twice, the
#                                    openai-community copy of GPT-2, five
#                                    mirrors of our own Hub models)
#   ~/.triton/cache                  Triton JIT cache, rebuilt on first use
#   ~/.cache/pip                     pip wheel cache
#   scratch fineweb_edu_100bt        empty directory
#   scratch fineweb_100bt_parquet    FineWeb sample-100BT download (150
#                                    parquet files, revision 9bb295dd); its
#                                    manifest.json with per-file sha256 is
#                                    committed as
#                                    results/fineweb_100bt_parquet_manifest.json
#                                    and must match before the removal; the
#                                    419 tokenized shards in
#                                    fineweb_100bt_tok32k stay; re-download
#                                    with slurm/fineweb100bt_download_cpu.sh
#
# Not touched: the inputs of the queued A@1e-3 chains (fineweb_edu_10bt,
# finemath_4plus, codeparrot_py), every checkpoint and snapshot, the tok32k
# shards, the scratch hf_cache, ~/ckpt_backup, the synthetic-task result
# directories under results/, the hub cache's datasets-- entries, and any
# directory outside this project.
set -u
H=/users/PAS2402/alexg
R=$H/softmax/softmax-is-meh
HUB=$H/.cache/huggingface/hub
S=/fs/scratch/PAS2836/alexg
DRY=${DRY:-0}
total_kb=0

rm_path() {
    local p=$1 kb
    if [ ! -e "$p" ]; then
        echo "missing  $p"
        return
    fi
    kb=$(du -sk -- "$p" | cut -f1)
    total_kb=$((total_kb + kb))
    echo "$(du -sh -- "$p" | cut -f1)	$p"
    if [ "$DRY" = 1 ]; then
        return
    fi
    rm -rf -- "$p"
}

echo "cleanup 2026-11-09 start $(date) DRY=$DRY"

rm_path "$R/results/mqmtar_data"

for m in \
    models--google--gemma-2-2b \
    models--canrager--saebench_gemma-2-2b_width-2pow16_date-0107 \
    models--google--gemma-1.1-2b-it \
    models--openai-community--gpt2-medium \
    models--gpt2-medium \
    models--google-t5--t5-small \
    models--openai-community--gpt2 \
    models--GulkoA--stilt.1.1-355m-nope-it \
    models--GulkoA--stilt.1.1-355m-nope-softmax-baseline \
    models--GulkoA--stilt.1-124m \
    models--GulkoA--stilt.1-124m-it \
    models--GulkoA--stilt.1-355m-it
do
    rm_path "$HUB/$m"
done
if [ -d "$HUB/models--gpt2" ]; then
    echo "kept     $HUB/models--gpt2"
else
    echo "WARNING: $HUB/models--gpt2 is missing; the convert and upload tools need it"
fi

if ls -l /proc/[0-9]*/fd 2>/dev/null | grep -q "/.triton/"; then
    echo "skipped  $H/.triton/cache (a process has it open)"
else
    rm_path "$H/.triton/cache"
fi

rm_path "$H/.cache/pip"

rm_path "$S/fineweb_edu_100bt"

if cmp -s -- "$S/fineweb_100bt_parquet/manifest.json" "$R/results/fineweb_100bt_parquet_manifest.json"; then
    rm_path "$S/fineweb_100bt_parquet"
else
    echo "skipped  $S/fineweb_100bt_parquet (committed manifest copy missing or different)"
fi

echo "cleanup 2026-11-09 end $(date): $((total_kb / 1024 / 1024)) GiB listed$([ "$DRY" = 1 ] && echo ', nothing removed (DRY=1)' || echo ' and removed')"
